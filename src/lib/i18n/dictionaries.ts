// Dotted-path key union derived from the Italian shape, for autocomplete and
// compile-time safety at call sites.
type Join<P extends string, C extends string> = P extends "" ? C : `${P}.${C}`;
type DeepKeys<T, P extends string = ""> = {
  [K in keyof T & string]: T[K] extends string
    ? Join<P, K>
    : DeepKeys<T[K], Join<P, K>>;
}[keyof T & string];

export type TranslationKey = DeepKeys<typeof it>;
export type Dictionary = DeepStringRecord;
